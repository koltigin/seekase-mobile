function item(
  id: string,
  collectionId: string,
  title: string,
  year: string | undefined,
  image: (typeof covers)[keyof typeof covers],
  extras: Partial<CollectibleItem> = {},
): CollectibleItem {
  return {
    id,
    collectionId,
    title,
    year,
    image,
    status: 'in-collection',
    ...extras,
  }
}

